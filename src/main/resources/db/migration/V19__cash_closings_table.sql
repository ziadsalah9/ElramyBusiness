-- =============================================================
-- V19: cash_closings for databases built by Flyway alone.
-- -------------------------------------------------------------
-- cash_closings was first created by Hibernate (ddl-auto=update), never
-- by a migration, so a fresh install had no such table. This creates it
-- exactly as the existing shop database has it; there every statement is
-- skipped (IF NOT EXISTS / guarded), so nothing changes.
-- Also aligns the archived price history column with the existing
-- database (NUMERIC(7,2), see V6).
-- =============================================================

CREATE TABLE IF NOT EXISTS cash_closings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMP(6),
    updated_at       TIMESTAMP(6),
    cash_sales_total NUMERIC(38, 2) NOT NULL,
    closing_date     DATE           NOT NULL,
    count10          INTEGER,
    count100         INTEGER,
    count20          INTEGER,
    count200         INTEGER,
    count5           INTEGER,
    count50          INTEGER,
    counted_total    NUMERIC(38, 2) NOT NULL,
    difference       NUMERIC(38, 2) NOT NULL,
    notes            VARCHAR(255),
    branch_id        BIGINT         NOT NULL REFERENCES branches (id),
    closed_by        BIGINT REFERENCES users (id),
    CONSTRAINT cash_closings_branch_date_key UNIQUE (branch_id, closing_date)
);

CREATE INDEX IF NOT EXISTS idx_cash_closings_branch ON cash_closings (branch_id);

